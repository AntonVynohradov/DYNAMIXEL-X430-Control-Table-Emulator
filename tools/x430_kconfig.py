"""Kconfig processing for the sfs-dynamixel-x430 CMake build."""

from __future__ import annotations

import argparse
import hashlib
import os
import pathlib
import sys
from typing import List

try:
    import kconfiglib
except ImportError:  # pragma: no cover - reported by CMake
    sys.exit("x430_kconfig.py: Kconfiglib is required (pip install kconfiglib)")


def _inputs_digest(kconfig: pathlib.Path, fragments: List[pathlib.Path]) -> str:
    digest = hashlib.sha256()
    digest.update(str(kconfig.resolve()).encode())
    for fragment in fragments:
        digest.update(str(fragment.resolve()).encode())
        digest.update(fragment.read_bytes())
    return digest.hexdigest()


def _cmake_value(sym: "kconfiglib.Symbol") -> str:
    value = sym.str_value
    if sym.type in (kconfiglib.BOOL, kconfiglib.TRISTATE):
        return "y" if value == "y" else ""
    return value.replace("\\", "\\\\").replace('"', '\\"')


def _write_cmake(kconf: "kconfiglib.Kconfig", path: pathlib.Path, prefix: str) -> None:
    lines = ["# Generated by tools/x430_kconfig.py - do not edit.", ""]
    for sym in kconf.unique_defined_syms:
        if sym.type == kconfiglib.UNKNOWN or not sym.name.startswith(prefix):
            continue
        lines.append(f'set({kconf.config_prefix}{sym.name} "{_cmake_value(sym)}")')
    text = "\n".join(lines) + "\n"
    if not path.is_file() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")


def _write_if_changed(path: pathlib.Path, writer) -> None:
    """Writes through a temporary file so unchanged outputs keep their timestamp."""
    temporary = path.with_suffix(path.suffix + ".tmp")
    writer(str(temporary))
    if path.is_file() and path.read_bytes() == temporary.read_bytes():
        temporary.unlink()
    else:
        os.replace(temporary, path)


def configure(args: argparse.Namespace) -> int:
    kconfig = pathlib.Path(args.kconfig)
    fragments = [pathlib.Path(f) for f in args.fragments if f]
    config = pathlib.Path(args.config)
    stamp = config.with_name(config.name + ".inputs")
    digest = _inputs_digest(kconfig, fragments)

    os.environ.setdefault("srctree", str(kconfig.parent))
    kconf = kconfiglib.Kconfig(str(kconfig), warn_to_stderr=False)
    kconf.warn_assign_undef = True       # typo in a fragment: report it
    kconf.warn_assign_override = False   # later fragments may override earlier ones

    keep = config.is_file() and stamp.is_file() and stamp.read_text().strip() == digest
    if keep:
        kconf.load_config(str(config))
        source = f"{config} (kept: fragments unchanged)"
    else:
        for index, fragment in enumerate(fragments):
            kconf.load_config(str(fragment), replace=(index == 0))
        source = ", ".join(str(f) for f in fragments) or "Kconfig defaults"

    for warning in kconf.warnings:
        print(f"x430 Kconfig warning: {warning}", file=sys.stderr)
    if args.strict and kconf.warnings:
        print("x430 Kconfig: warnings are errors (--strict)", file=sys.stderr)
        return 1

    config.parent.mkdir(parents=True, exist_ok=True)
    _write_if_changed(config, lambda p: kconf.write_config(p, header="# Generated: x430 Kconfig\n"))
    stamp.write_text(digest + "\n")
    header = pathlib.Path(args.header)
    header.parent.mkdir(parents=True, exist_ok=True)
    _write_if_changed(header, kconf.write_autoconf)
    _write_cmake(kconf, pathlib.Path(args.cmake), args.cmake_prefix)
    print(f"x430 Kconfig: configuration from {source}")
    return 0


def savedefconfig(args: argparse.Namespace) -> int:
    kconfig = pathlib.Path(args.kconfig)
    os.environ.setdefault("srctree", str(kconfig.parent))
    kconf = kconfiglib.Kconfig(str(kconfig), warn_to_stderr=False)
    kconf.load_config(args.config)
    kconf.write_min_config(args.output)
    print(f"x430 Kconfig: minimal configuration written to {args.output}")
    return 0


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--kconfig", required=True, help="top-level Kconfig file")
    parser.add_argument("--config", required=True, help=".config in the build directory")
    sub = parser.add_subparsers(dest="command", required=True)

    run = sub.add_parser("configure", help="merge fragments, write header and CMake include")
    run.add_argument("--header", required=True)
    run.add_argument("--cmake", required=True)
    run.add_argument("--cmake-prefix", default="X430_", help="symbols exported to CMake")
    run.add_argument("--strict", action="store_true", help="fail on Kconfig warnings")
    run.add_argument("fragments", nargs="*")

    save = sub.add_parser("savedefconfig", help="write a minimal configuration")
    save.add_argument("--output", required=True)

    args = parser.parse_args(argv)
    if args.command == "configure":
        return configure(args)
    return savedefconfig(args)


if __name__ == "__main__":
    sys.exit(main())
